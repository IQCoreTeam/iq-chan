#!/usr/bin/env node
// Scans public/randombanners and public/noimage at build time
// and writes the file lists to src/lib/generated-images.ts
// Run automatically via "prebuild" in package.json

const fs = require("fs");
const path = require("path");

function scanDir(dir, urlPrefix) {
    const full = path.join(__dirname, "..", "public", dir);
    if (!fs.existsSync(full)) return [];
    return fs.readdirSync(full)
        .filter((f) => /\.(png|jpe?g|webp|gif|svg)$/i.test(f))
        .sort()
        .map((f) => `${urlPrefix}/${f}`);
}

const banners = scanDir("randombanners", "/randombanners");
const placeholders = scanDir("noimage", "/noimage");
const hoodBanners = scanDir("hoodchan/banners", "/hoodchan/banners");
const hoodPlaceholders = scanDir("hoodchan/noimage", "/hoodchan/noimage");

const out = `// Auto-generated by scripts/gen-image-lists.js — do not edit manually
export const RANDOM_BANNERS: string[] = ${JSON.stringify(banners, null, 4)};

export const NO_IMAGE_PLACEHOLDERS: string[] = ${JSON.stringify(placeholders, null, 4)};

export const BANNERS_BY_DIR: Record<string, string[]> = {
    "hoodchan/banners": ${JSON.stringify(hoodBanners, null, 4)}
};

export const PLACEHOLDERS_BY_DIR: Record<string, string[]> = {
    "hoodchan/noimage": ${JSON.stringify(hoodPlaceholders, null, 4)}
};
`;

const dest = path.join(__dirname, "..", "src", "lib", "generated-images.ts");
fs.writeFileSync(dest, out);
console.log(`Generated ${dest}: ${banners.length} banners, ${placeholders.length} placeholders`);
